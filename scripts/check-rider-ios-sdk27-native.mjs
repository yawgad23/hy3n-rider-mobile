import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

if (process.env.EAS_BUILD_PLATFORM === 'android') process.exit(0);
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const require = createRequire(join(root, 'package.json'));
const plist = require('@expo/plist').default;
const assert = (condition, message) => { if (!condition) throw new Error(`[Rider iOS SDK 27] ${message}`); };
const read = filename => readFileSync(join(root, filename), 'utf8');
const json = filename => JSON.parse(read(filename));
const manifest = json('package.json');
const eas = json('eas.json');
assert(eas.build.production.ios.image === 'macos-tahoe-26.6-xcode-27.0', 'The explicit Xcode 27 production image is required.');
assert(require('expo/package.json').version === '57.0.34', 'Unsupported Expo source graph.');
assert(require('react-native/package.json').version === '0.86.3', 'Unsupported React Native source graph.');
assert(require('react-native-maps/package.json').version === '1.29.11', 'The audited native Google Marker Fabric fixes are required.');
assert(manifest.dependencies['hy3n-backend'] === 'github:yawgad23/backend#275b227a2ddeb2db157b1f6b061ffeea312e6ea1', 'Backend lock revision changed.');
const info = plist.parse(read('ios/HY3N/Info.plist'));
const props = json('ios/Podfile.properties.json');
const delegate = read('ios/HY3N/AppDelegate.swift');
const podfile = read('ios/Podfile');
const project = read('ios/HY3N.xcodeproj/project.pbxproj');
assert(info.CFBundleShortVersionString === '1.0.6' && info.CFBundleVersion === '139', 'Unexpected iOS release identity.');
assert(project.includes('com.hy3n.rider'), 'Rider bundle identity is missing.');
assert(props['ios.deploymentTarget'] === '16.4', 'The approved minimum iOS 16.4 target is required.');
assert(props['expo.useHermesV1'] === 'true', 'SDK 57 Hermes V1 must be enabled.');
assert(props.EXPO_USE_PRECOMPILED_MODULES === 'false', 'Audited Apple Swift sources must compile rather than use precompiled modules.');
assert(props['ios.useFrameworks'] === 'static', 'Firebase 25.1 CocoaPods requires static frameworks.');
assert(JSON.stringify(JSON.parse(props['ios.forceStaticLinking'])) === JSON.stringify(['RNFBApp', 'RNFBMessaging']), 'Only the installed native Firebase pods must be force-static linked.');
assert(podfile.includes('$RNFirebaseAsStaticFramework = true'), 'Firebase static-framework override is missing.');
assert(podfile.includes("pod 'react-native-maps/Google'") && !podfile.includes("pod 'react-native-google-maps'"), 'The modern Google Maps subspec must be linked.');
assert(!podfile.includes('use_modular_headers!'), 'Do not globally modularize React Native headers.');
const scenes = info.UIApplicationSceneManifest?.UISceneConfigurations?.UIWindowSceneSessionRoleApplication;
assert(scenes?.length === 1 && scenes[0].UISceneDelegateClassName === 'EXExpoAppSceneDelegate', 'Expo SDK 57 scene lifecycle must be enabled.');
assert(delegate.includes('ExpoReactNativeFactoryProvider') && !delegate.includes('factory.startReactNative('), 'AppDelegate must use the scene-provided React factory, not legacy window startup.');
const mapsCalls = [...delegate.matchAll(/GMSServices\.provideAPIKey\("([^"\n]+)"\)/g)];
assert(mapsCalls.length === 1 && Boolean(info.GMSApiKey) && mapsCalls[0][1] === info.GMSApiKey, 'Exactly one native Maps key must match Info.plist; no values are logged.');
assert(mapsCalls[0].index < delegate.indexOf('let delegate =') && mapsCalls[0].index < delegate.indexOf('return super.application'), 'Initialize Google Maps before any React factory or scene launch.');
assert((delegate.match(/FirebaseApp\.configure\(/g) || []).length === 1, 'Firebase must initialize exactly once.');
assert(!delegate.includes('FirebaseAuth') && !delegate.includes('RCTLinkingManager.scene'), 'Rider must not inherit Driver native-auth/custom scene dispatch.');
const appleRoot = dirname(require.resolve('expo-apple-authentication/package.json'));
const request = readFileSync(join(appleRoot, 'ios/AppleAuthenticationRequest.swift'), 'utf8');
assert(request.includes('foregroundKeyWindow()') && request.includes('presentationAnchorWindow') && request.includes('Thread.isMainThread'), 'The audited main-thread, retained-anchor Apple patch must be present.');
assert(!request.includes('application.windows') && !request.includes('UIApplication.shared.windows'), 'Apple presentation must select a foreground scene only.');
const entitlements = plist.parse(read('ios/HY3N/HY3N.entitlements'));
assert(entitlements['com.apple.developer.applesignin']?.includes('Default'), 'Apple sign-in entitlement is missing.');
if (process.env.EAS_BUILD_PROFILE === 'production') assert(entitlements['aps-environment'] === 'production', 'Production APNs entitlement is required.');
if (process.env.EAS_BUILD === 'true') {
  const support = join(root, 'ios/Pods/Target Support Files');
  const providers = existsSync(support) ? readdirSync(support).map(name => join(support, name, 'ExpoModulesProvider.swift')).filter(existsSync) : [];
  assert(providers.some(filename => readFileSync(filename, 'utf8').includes('AppleAuthenticationModule.self')), 'CocoaPods must generate the actual Apple module provider before compilation.');
}
console.log('[Rider iOS SDK 27] PASS: identity 1.0.6/139, iOS16.4, scenes, native Maps startup/key presence, Firebase linkage and audited Apple sources.');
console.log('[Rider iOS SDK 27] Native source gate only. Confirm the finished signed IPA DTSDKName is iphoneos27.* before TestFlight upload.');
